"""Флаги скрытых функций (feature flags).

Проект развивается поэтапно: часть функционала уже реализована в коде,
но временно скрыта из интерфейса и помечена как «добавим в обновлениях».
Функционал при этом НЕ удаляется — достаточно переключить флаг ниже
(или задать переменную окружения ``FEATURE_<ИМЯ>``), чтобы всё снова заработало.

Текущие флаги:
- COURSES — курсы для ученика и курсовые разделы у учителя.
  По умолчанию выключен: ученик не видит список/каталог своих курсов и
  не может записаться на курс; учитель видит раздел «Курсы» с плашкой
  «Добавим в обновлениях». Привязка ученика к учителю работает напрямую
  (модель StudentTeacherLink) и от этого флага не зависит.
"""

import os


def _env_flag(name, default=False):
    value = os.getenv(f"FEATURE_{name}")
    if value is None:
        return default
    return value.strip().lower() in ("true", "1", "yes", "on")


def courses_enabled():
    """Показывать ли курсовой функционал (ученику — его курсы, учителю — управление курсами)."""
    return _env_flag("COURSES", default=False)
